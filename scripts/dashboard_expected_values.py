"""Write docs/dashboard/expected_values.md: known-good numbers for checking the Power BI dashboard.

    python scripts/dashboard_expected_values.py

Every number is computed directly in SQL against the `bi` star schema, independently of any DAX. If a
Power BI visual disagrees with this file, the DAX or the model (relationship, data type, filter) is wrong.
"""
from pathlib import Path

import duckdb

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "dashboard" / "expected_values.md"
con = duckdb.connect(str(ROOT / "data" / "healthcare.duckdb"), read_only=True)


def rows(sql):
    return con.execute(sql).fetchall()


def table(headers, data, fmts):
    out = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    for r in data:
        out.append("| " + " | ".join(f.format(v) for f, v in zip(fmts, r)) + " |")
    return "\n".join(out)


KPI = """
select count(*) admissions, count(distinct patient_id) patients, avg(length_of_stay_days) avg_los,
       sum(total_claim_cost) total_cost, sum(is_index_admission) idx, sum(readmitted_30d) readm,
       100.0 * sum(readmitted_30d) / sum(is_index_admission) rate
from bi.fact_admissions f join bi.dim_date d on f.admit_date = d.date {where}"""
KPI_H = ["Admissions", "Unique patients", "Avg LOS (days)", "Total claim cost ($)", "Index admissions",
         "Readmissions 30d", "30-day readmission rate (%)"]
KPI_F = ["{:,}", "{:,}", "{:.2f}", "{:,.0f}", "{:,}", "{:,}", "{:.2f}"]

md = ["# Expected values for the Power BI dashboard", "",
      "Generated by `scripts/dashboard_expected_values.py` from the `bi` star schema. Compare each Power BI visual to the",
      "matching row. A mismatch means a modelling or DAX problem, not a data problem.", ""]

md += ["## 1. KPI cards", "", "**No filters (all years, 1922-2026):**", "",
       table(KPI_H, rows(KPI.format(where="")), KPI_F), "",
       "**With the recommended Year slicer 2015-2025:**", "",
       table(KPI_H, rows(KPI.format(where="where d.year between 2015 and 2025")), KPI_F), ""]

md += ["## 2. Admissions and readmission rate by ICD-10 chapter (no filters)", "",
       table(["ICD-10 chapter", "Admissions", "Index admissions", "Readmission rate (%)", "Share of admissions (%)"],
             rows("""select icd10_chapter, count(*), sum(is_index_admission),
                            100.0 * sum(readmitted_30d) / sum(is_index_admission),
                            100.0 * count(*) / sum(count(*)) over ()
                     from bi.fact_admissions group by 1 order by 2 desc"""),
             ["{}", "{:,}", "{:,}", "{:.2f}", "{:.1f}"]), "",
       "Chapters with fewer than 30 index admissions have unstable rates; the `Rate (min volume)` measure blanks them.", ""]

md += ["## 3. Readmission rate by age group (no filters)", "",
       table(["Age group", "Index admissions", "Readmission rate (%)"],
             rows("""select age_group, sum(is_index_admission), 100.0 * sum(readmitted_30d) / sum(is_index_admission)
                     from bi.fact_admissions group by 1 order by 1"""), ["{}", "{:,}", "{:.2f}"]), "",
       "## 4. Readmission rate by year, 2018-2025 (no other filters)", "",
       table(["Year", "Index admissions", "Readmission rate (%)"],
             rows("""select d.year, sum(is_index_admission), 100.0 * sum(readmitted_30d) / sum(is_index_admission)
                     from bi.fact_admissions f join bi.dim_date d on f.admit_date = d.date
                     where d.year between 2018 and 2025 group by 1 order by 1"""), ["{}", "{:,}", "{:.2f}"]), ""]

md += ["## 5. Chronic-condition prevalence (denominator = all 5,733 patients, no filters)", "",
       table(["Chronic group", "Patients", "Prevalence (%)"],
             rows("""select chronic_group, count(distinct patient_id),
                            100.0 * count(distinct patient_id) / (select count(*) from bi.dim_patient)
                     from bi.fact_chronic_conditions group by 1 order by 2 desc"""), ["{}", "{:,}", "{:.2f}"]), "",
       "**Hypertension prevalence by age band** (denominator = patients in that band):", "",
       table(["Age band", "Patients in band", "With hypertension", "Prevalence (%)"],
             rows("""select age_band, count(*), sum(has_hypertension), 100.0 * sum(has_hypertension) / count(*)
                     from bi.dim_patient group by 1 order by 1"""), ["{}", "{:,}", "{:,}", "{:.2f}"]), "",
       "**Comorbidity** (patients with 2 or more chronic conditions):", "",
       table(["Patients", "With 2+ conditions", "Comorbidity (%)"],
             rows("""select count(*), sum((chronic_condition_count >= 2)::int),
                            100.0 * sum((chronic_condition_count >= 2)::int) / count(*) from bi.dim_patient"""),
             ["{:,}", "{:,}", "{:.2f}"]), "",
       "**Diabetes prevalence, 5 largest counties by patient count:**", "",
       table(["County", "Patients", "With diabetes", "Prevalence (%)"],
             rows("""select county, count(*), sum(has_diabetes), 100.0 * sum(has_diabetes) / count(*)
                     from bi.dim_patient group by 1 order by 2 desc limit 5"""), ["{}", "{:,}", "{:,}", "{:.2f}"]), ""]

md += ["## 6. Top 5 ICD-10 codes by admissions (no filters)", "",
       table(["ICD-10", "Description", "Admissions", "Readmission rate (%)"],
             rows("""select f.icd10_code, any_value(i.icd10_description), count(*),
                            100.0 * sum(readmitted_30d) / sum(is_index_admission)
                     from bi.fact_admissions f join bi.dim_icd10 i using (icd10_code)
                     group by 1 order by 3 desc limit 5"""), ["{}", "{}", "{:,}", "{:.2f}"]), ""]

OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text("\n".join(md), encoding="utf-8")
print(f"wrote {OUT.relative_to(ROOT)} ({len(md)} blocks)")
